"""Ready-made designs a visitor can load, edit and re-check, and the JSON Schema of an editable design.

Files (committed, regenerated by `python -m siliconsmith.board.templates --write`; a test keeps them in sync):
    templates/clean_sensor.json             the clean battery environmental sensor reference design
    templates/fault_gpio12_vs_gpio14.json   firmware header says GPIO12, the netlist wires GPIO14 (pin_mismatch)
    templates/fault_strapping_pin.json      wake button wired and declared on GPIO12, a strapping pin
    design.schema.json                      JSON Schema of a design plus the accepted limits and assumption ranges
Each template file is {id, title, description, expect, design, header}: `expect` is the status per rung the checker
gives today (verified by the tests), `header` the C pin header our generator writes for the design.
"""

from __future__ import annotations

import json
from pathlib import Path

from .checks import IMPLEMENTED_RUNGS, run_ladder
from .export import firmware_header
from .faults import inject_fault, reference_design
from .limits import (ASSUMPTION_CHOICES, ASSUMPTION_RANGES, MAX_BODY_BYTES, MAX_BRIEF_CHARS, MAX_HEADER_BYTES,
                     MAX_INSTANCES, MAX_NETS, MAX_PINS_PER_NET, MAX_STRING)
from .netlist import Design
from .parts import load_library

TEMPLATES_DIR = Path(__file__).parent / "templates"
SCHEMA_FILE = Path(__file__).parent / "design.schema.json"

SPECS = [
    {"id": "clean_sensor", "title": "Clean battery sensor",
     "description": "ESP32 module, BME280 sensor on I2C, LDO, Li-ion cell, charger and USB-C. Passes every rung.",
     "fault": None},
    {"id": "fault_gpio12_vs_gpio14", "title": "Fault: firmware GPIO12, netlist GPIO14",
     "description": "The firmware pin header puts the wake button on GPIO12 but the netlist wires it to GPIO14. "
                    "GPIO12 is also a strapping pin. Rung B4 flags it.",
     "fault": "pin_mismatch"},
    {"id": "fault_strapping_pin", "title": "Fault: wake button on a strapping pin",
     "description": "The wake button is wired and declared on GPIO12, a boot-strapping pin, so firmware and netlist "
                    "agree but the pin is hazardous. Rung B4 flags it.",
     "fault": "strapping_pin_misuse"},
]


def build_template(spec: dict) -> dict:
    design = reference_design() if spec["fault"] is None else inject_fault(reference_design(), spec["fault"])
    library = load_library()
    header = firmware_header(design)
    results = run_ladder(design, library, header)
    return {"id": spec["id"], "title": spec["title"], "description": spec["description"],
            "expect": {r.rung: r.status for r in results},
            "design": json.loads(design.model_dump_json()), "header": header}


def design_schema() -> dict:
    schema = Design.model_json_schema()
    schema["title"] = "Board design"
    schema["description"] = (
        "A netlist-level board design. Nets list connected pins as REF.PIN. 'assumptions' are inputs the checks need "
        "but a netlist cannot state; only the keys in x-assumptions are accepted. Parts come from the parts library "
        "(GET /api/board/parts); unknown parts make rungs report unknown, never pass.")
    schema["x-limits"] = {"max_body_bytes": MAX_BODY_BYTES, "max_header_bytes": MAX_HEADER_BYTES,
                          "max_brief_chars": MAX_BRIEF_CHARS, "max_instances": MAX_INSTANCES, "max_nets": MAX_NETS,
                          "max_pins_per_net": MAX_PINS_PER_NET, "max_string": MAX_STRING}
    schema["x-assumptions"] = {**{k: {"type": "number", "min": lo, "max": hi} for k, (lo, hi) in ASSUMPTION_RANGES.items()},
                               **{k: {"enum": list(v)} for k, v in ASSUMPTION_CHOICES.items()}}
    schema["x-rungs"] = list(IMPLEMENTED_RUNGS)
    return schema


def template_files() -> dict[Path, str]:
    out = {TEMPLATES_DIR / f"{s['id']}.json": json.dumps(build_template(s), indent=2) + "\n" for s in SPECS}
    out[SCHEMA_FILE] = json.dumps(design_schema(), indent=2) + "\n"
    return out


def load_template(template_id: str) -> dict:
    f = TEMPLATES_DIR / f"{template_id}.json"
    if not f.is_file() or template_id not in {s["id"] for s in SPECS}:
        raise KeyError(template_id)
    return json.loads(f.read_text(encoding="utf-8"))


def list_templates() -> list[dict]:
    return [{k: t[k] for k in ("id", "title", "description", "expect")} for t in (load_template(s["id"]) for s in SPECS)]


if __name__ == "__main__":
    import sys

    if "--write" in sys.argv:
        TEMPLATES_DIR.mkdir(exist_ok=True)
        for path, text in template_files().items():
            path.write_text(text, encoding="utf-8", newline="\n")
            print("wrote", path.name)
    else:
        print("use --write to regenerate the template and schema files")
