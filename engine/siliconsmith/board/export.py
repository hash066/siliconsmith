"""Deterministic exports from a design: firmware pin header (C), BOM, KiCad netlist (.net).

Nothing here is a layout. The KiCad netlist carries no footprints, so it cannot be turned into a board without
assigning them; the BOM lists parts and values as the design states them, with no manufacturer part numbers.
"""

from __future__ import annotations

import re

from .netlist import Design
from .parts import Part

_GPIO_RE = re.compile(r"^GPIO(\d+)$")


def _macro(function: str) -> str:
    return "SS_PIN_" + re.sub(r"[^A-Za-z0-9]+", "_", function).strip("_").upper()


def firmware_header(design: Design) -> str:
    """C pin header for the design's firmware pin table (`firmware_pins`). Raises ValueError for a pin that is not
    a GPIO name, since the header would have nothing to put in the number."""
    lines = [
        "/* Generated by siliconsmith.board.export from the design's firmware pin table. Do not edit.",
        f" * Design: {design.name}",
        " * Rung B4 compares this table with the netlist; this file alone proves nothing. */",
        "#ifndef SS_BOARD_PINS_H",
        "#define SS_BOARD_PINS_H",
        "",
    ]
    for f in design.firmware_pins:
        m = _GPIO_RE.match(f.pin)
        if not m:
            raise ValueError(f"{f.function}: {f.pin!r} is not a GPIO pin name")
        lines.append(f"#define {_macro(f.function)} {int(m.group(1))}  /* {f.use} */")
    lines += ["", "#endif /* SS_BOARD_PINS_H */", ""]
    return "\n".join(lines)


def _value(inst, part: Part) -> str:
    ohms = inst.params.get("ohms")
    if isinstance(ohms, (int, float)):
        return f"{ohms:g} ohm"
    return part.name


def bom(design: Design, library: dict[str, Part]) -> list[dict[str, str]]:
    """One row per distinct (part, value), refs sorted. Unknown parts are listed with their id, never dropped."""
    rows: dict[tuple[str, str], list[str]] = {}
    meta: dict[tuple[str, str], dict[str, str]] = {}
    for inst in design.instances:
        part = library.get(inst.part)
        value = _value(inst, part) if part else inst.part
        key = (inst.part, value)
        rows.setdefault(key, []).append(inst.ref)
        meta[key] = {
            "part": inst.part,
            "name": part.name if part else "(not in parts library)",
            "value": value,
            "origin": part.origin if part else "unknown",
        }
    out = []
    for key in sorted(rows):
        refs = sorted(rows[key], key=lambda r: (re.sub(r"\d+$", "", r), int(re.search(r"\d+$", r).group()) if re.search(r"\d+$", r) else 0))
        out.append({**meta[key], "refs": ", ".join(refs), "quantity": str(len(refs))})
    return out


def _q(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def kicad_netlist(design: Design, library: dict[str, Part]) -> str:
    """KiCad s-expression netlist (.net): components with value and part, nets with pad numbers. No footprints."""
    out = ["(export (version \"E\")",
           f"  (design (source {_q(design.name)}) (tool \"siliconsmith.board.export\"))",
           "  (components"]
    for inst in design.instances:
        part = library.get(inst.part)
        out.append(f"    (comp (ref {_q(inst.ref)}) (value {_q(_value(inst, part) if part else inst.part)}) (footprint \"\")")
        out.append(f"      (libsource (lib \"siliconsmith\") (part {_q(inst.part)}) "
                   f"(description {_q(part.name if part else 'not in parts library')})))")
    out.append("  )")
    out.append("  (nets")
    for code, net in enumerate((n for n in design.nets if n.pins), start=1):
        out.append(f"    (net (code {_q(str(code))}) (name {_q(net.name)})")
        for ref_pin in net.pins:
            ref, _, pin = ref_pin.partition(".")
            inst = design.instance(ref)
            part = library.get(inst.part) if inst else None
            rec = part.pin(pin) if part else None
            number = rec.number if rec else pin
            out.append(f"      (node (ref {_q(ref)}) (pin {_q(number)}) (pinfunction {_q(pin)}))")
        out[-1] += ")"
    out.append("  ))")
    return "\n".join(out) + "\n"
