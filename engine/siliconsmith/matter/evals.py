"""Matter evals from docs/WORKSTATION_PLAN.md section 10, as code.

    python -m siliconsmith.matter.evals RUN_DIR [RUN_DIR ...] [--write PATH]

Targets (fixed in the plan before any run, never edited after seeing results):
  * solver validation: all within thresholds
  * agent beats the equal-material rectangular-fin baseline in at least 1 of 3 runs
  * second-solver agreement within 3% on each run's winner
The winner is RE-DERIVED here: its generator code is re-run from the saved file with the saved parameters,
and the peak must reproduce the number recorded in the run, so the eval does not trust the run's own claims.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

from . import generators, ladder
from . import thresholds as th
from .export import mask_to_stl, stl_stats
from .problem import Spreader, solve_mask, force_chip


def eval_run(run_dir: Path) -> dict:
    res = json.loads((run_dir / "results.json").read_text(encoding="utf-8"))
    out = dict(run=run_dir.name, cost_usd=res["cost_usd"], tokens=res["tokens"], nodes=len(res["nodes"]),
               best=res["best_node_id"], all_rungs=res["all_rungs_passed"], baseline_full=res["baseline_peak_c"])
    if not res["best_node_id"]:
        return out | dict(reproduced=False, note="no feasible winner")
    nid = res["best_node_id"]
    sp = Spreader(**res["spreader"])
    node = json.loads((run_dir / "nodes" / nid / "result.json").read_text(encoding="utf-8"))
    code = (run_dir / "nodes" / nid / "generator.py").read_text(encoding="utf-8")
    g = generators.run_generator(code, [node["params"]], sp.n, sp.chip_cells)[0]
    if not g.ok:
        return out | dict(reproduced=False, note=f"generator no longer runs: {g.error}")
    peak = solve_mask(force_chip(g.mask, sp), sp).peak
    m4 = ladder.m4_second_solver(g.mask, sp)
    m5 = ladder.m5_baseline(g.mask, sp)
    stl = stl_stats(mask_to_stl(g.mask, sp))
    out.update(
        winner_generator=res["nodes"][nid]["generator"], peak_recorded=node["metrics"]["peak_temp_c"], peak_rederived=peak,
        reproduced=abs(peak - node["metrics"]["peak_temp_c"]) < 1e-9,
        material_fraction=node["metrics"]["material_fraction"],
        m4=m4.status, fem_err=m4.data["fem_err"], refine_err=m4.data["refine_err"],
        m5=m5.status, delta_equal_material_k=m5.data["delta_k"], equal_material_baseline_c=m5.data["baseline_peak"],
        beats_full_budget_baseline=peak < res["baseline_peak_c"], stl_closed=stl["unmatched_edges"] == 0)
    return out


def summarize(rows: list[dict]) -> tuple[dict, str]:
    m1 = ladder.m1_solver_validated()
    beats = [r for r in rows if r.get("reproduced") and r.get("all_rungs") and r.get("m5") == "pass"]
    strict = [r for r in rows if r.get("beats_full_budget_baseline")]
    fem_ok = [r for r in rows if r.get("m4") == "pass" and r["fem_err"] <= th.SECOND_SOLVER_REL]
    ev = {
        "solver_validation": m1.status == "pass",
        "agent_beats_equal_material_baseline": f"{len(beats)}/{len(rows)} runs (target >= 1 of 3)",
        "agent_beats_equal_material_baseline_pass": len(beats) >= 1 and len(rows) >= 3,
        "agent_beats_full_budget_baseline_info": f"{len(strict)}/{len(rows)} runs (stricter, not a plan target)",
        "second_solver_within_3pct": f"{len(fem_ok)}/{len(rows)} winners",
        "second_solver_pass": len(fem_ok) == len([r for r in rows if r.get("best")]) > 0,
    }
    L = ["# Matter evals (measured)", "",
         "Generated by `python -m siliconsmith.matter.evals`. Thresholds and targets were fixed before any run.", "",
         f"* Solver validation (M1): **{'PASS' if ev['solver_validation'] else 'FAIL'}** ({m1.detail})",
         f"* Agent beats equal-material rectangular-fin baseline: **{'PASS' if ev['agent_beats_equal_material_baseline_pass'] else 'FAIL'}**, {ev['agent_beats_equal_material_baseline']}",
         f"* Info: {ev['agent_beats_full_budget_baseline_info']} beat the full-budget baseline",
         f"* Second solver agreement (limit {th.SECOND_SOLVER_REL:.0%}): **{'PASS' if ev['second_solver_pass'] else 'FAIL'}**, {ev['second_solver_within_3pct']}", "",
         "| run | winner | peak C | material | rungs M1-M5 | vs equal-material baseline | vs full-budget baseline | FEM err | cost USD | reproduced |",
         "|---|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        if not r.get("winner_generator"):
            L.append(f"| {r['run']} | none | - | - | - | - | - | - | {r['cost_usd']:.4f} | - |")
            continue
        L.append(f"| {r['run']} | {r['winner_generator']} ({r['best']}) | {r['peak_rederived']:.2f} | {r['material_fraction']:.1%} | "
                 f"{'all pass' if r['all_rungs'] else 'not all'} | {r['delta_equal_material_k']:+.2f} K (baseline {r['equal_material_baseline_c']:.2f} C) | "
                 f"{'beats' if r['beats_full_budget_baseline'] else 'does not beat'} {r['baseline_full']:.2f} C | {r['fem_err']:.2%} | {r['cost_usd']:.4f} | {r['reproduced']} |")
    L.append("")
    return ev, "\n".join(L)


def main(argv: list[str]) -> int:
    write = None
    if "--write" in argv:
        i = argv.index("--write")
        write = Path(argv[i + 1])
        argv = argv[:i] + argv[i + 2:]
    rows = [eval_run(Path(a)) for a in argv]
    ev, md = summarize(rows)
    print(md)
    if write:
        write.write_text(md, encoding="utf-8")
    return 0 if all(v for k, v in ev.items() if k.endswith("_pass") or k == "solver_validation") else 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
