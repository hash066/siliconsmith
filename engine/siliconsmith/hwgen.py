"""Generate the custom-instruction slot (RTL + C intrinsics) for a CPU configuration.

Every custom instruction is an R-type instruction on the RISC-V custom-0 opcode:

    opcode = 0b0001011 (0x0B), funct3 = 0, funct7 = instruction id (0..127)

and is implemented as a purely combinational unit

    module ss_insn_<name>(input [31:0] rs1, input [31:0] rs2, output [31:0] rd);

which the generated dispatcher (ss_pcpi) registers and hands back to PicoRV32 over PCPI.
Restricting the agent to this template is what makes autonomous design reliable.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from pathlib import Path

CUSTOM0_OPCODE = 0x0B
_NAME_RE = re.compile(r"^[a-z][a-z0-9_]{0,30}$")


@dataclass(frozen=True)
class Instruction:
    """One custom instruction. `rtl` is the full Verilog module ss_insn_<name>;
    `c_ref` is the C body of `uint32_t f(uint32_t rs1, uint32_t rs2)` (the spec)."""

    name: str  # C-safe identifier, e.g. "dot4_s8"
    mnemonic: str  # display form, e.g. "dot4.s8"
    funct7: int
    rtl: str
    c_ref: str
    title: str = ""
    rationale: str = ""

    def __post_init__(self) -> None:
        if not _NAME_RE.match(self.name):
            raise ValueError(f"invalid instruction name {self.name!r}")
        if not 0 <= self.funct7 <= 127:
            raise ValueError(f"funct7 out of range for {self.name}: {self.funct7}")
        if f"module ss_insn_{self.name}" not in self.rtl:
            raise ValueError(f"rtl for {self.name} must define module ss_insn_{self.name}")

    @property
    def encoding(self) -> int:
        """Instruction word with rd=rs1=rs2=0, used for disassembly matching."""
        return (self.funct7 << 25) | CUSTOM0_OPCODE


@dataclass
class CpuConfig:
    instructions: list[Instruction] = field(default_factory=list)

    def __post_init__(self) -> None:
        names = [i.name for i in self.instructions]
        ids = [i.funct7 for i in self.instructions]
        if len(set(names)) != len(names) or len(set(ids)) != len(ids):
            raise ValueError("instruction names and funct7 ids must be unique")

    def next_funct7(self) -> int:
        used = {i.funct7 for i in self.instructions}
        return next(n for n in range(128) if n not in used)


def render_pcpi(cfg: CpuConfig) -> str:
    units = []
    cases = []
    for ins in cfg.instructions:
        units.append(
            f"\twire [31:0] rd_{ins.name};\n"
            f"\tss_insn_{ins.name} u_{ins.name} (.rs1(pcpi_rs1), .rs2(pcpi_rs2), .rd(rd_{ins.name}));"
        )
        cases.append(
            f"\t\t\t\t7'd{ins.funct7}: begin pcpi_ready <= 1'b1; pcpi_wr <= 1'b1; "
            f"pcpi_rd <= rd_{ins.name}; end  // {ins.mnemonic}"
        )
    units_s = "\n".join(units) if units else "\t// baseline: no custom instructions"
    cases_s = "\n".join(cases)
    return f"""// AUTO-GENERATED by SiliconSmith (hwgen.py). Do not edit by hand.
// Custom instructions: {", ".join(i.mnemonic for i in cfg.instructions) or "none (baseline)"}
`default_nettype none

module ss_pcpi (
	input  wire        clk,
	input  wire        resetn,
	input  wire        pcpi_valid,
	input  wire [31:0] pcpi_insn,
	input  wire [31:0] pcpi_rs1,
	input  wire [31:0] pcpi_rs2,
	output reg         pcpi_wr,
	output reg  [31:0] pcpi_rd,
	output wire        pcpi_wait,
	output reg         pcpi_ready
);
	wire is_custom0 = pcpi_valid && pcpi_insn[6:0] == 7'b0001011 && pcpi_insn[14:12] == 3'b000;
	wire [6:0] funct7 = pcpi_insn[31:25];

{units_s}

	assign pcpi_wait = 1'b0;

	always @(posedge clk) begin
		pcpi_wr    <= 1'b0;
		pcpi_ready <= 1'b0;
		pcpi_rd    <= 32'h0;
		if (resetn && is_custom0 && !pcpi_ready) begin
			case (funct7)
{cases_s}
				default: ;
			endcase
		end
	end
endmodule

`default_nettype wire
"""


def render_intrinsics(cfg: CpuConfig) -> str:
    lines = [
        "/* AUTO-GENERATED by SiliconSmith (hwgen.py). Do not edit by hand. */",
        "#pragma once",
        "#include <stdint.h>",
        "",
    ]
    for ins in cfg.instructions:
        lines += [
            f"/* {ins.mnemonic}: {ins.title} (custom-0, funct7={ins.funct7}) */",
            f"static inline uint32_t ss_ref_{ins.name}(uint32_t rs1, uint32_t rs2) {{",
            _indent(ins.c_ref.strip()),
            "}",
            "#ifdef __riscv",
            f"static inline uint32_t ss_{ins.name}(uint32_t rs1, uint32_t rs2) {{",
            "\tuint32_t rd;",
            f'\t__asm__(".insn r 0x0B, 0, {ins.funct7}, %0, %1, %2" : "=r"(rd) : "r"(rs1), "r"(rs2));',
            "\treturn rd;",
            "}",
            "#else",
            f"#define ss_{ins.name} ss_ref_{ins.name}",
            "#endif",
            "",
        ]
    return "\n".join(lines)


def _indent(body: str) -> str:
    return "\n".join("\t" + ln if ln.strip() else ln for ln in body.splitlines())


def write_config(cfg: CpuConfig, out_dir: Path) -> dict[str, Path]:
    """Write ss_pcpi.v, one file per instruction unit, and ss_intrinsics.h into out_dir."""
    out_dir.mkdir(parents=True, exist_ok=True)
    files: dict[str, Path] = {}
    p = out_dir / "ss_pcpi.v"
    p.write_text(render_pcpi(cfg), newline="\n")
    files["pcpi"] = p
    for ins in cfg.instructions:
        q = out_dir / f"ss_insn_{ins.name}.v"
        q.write_text(ins.rtl.strip() + "\n", newline="\n")
        files[f"insn:{ins.name}"] = q
    h = out_dir / "ss_intrinsics.h"
    h.write_text(render_intrinsics(cfg), newline="\n")
    files["intrinsics"] = h
    return files
